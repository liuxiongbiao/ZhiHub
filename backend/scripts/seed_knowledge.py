def clear_existing(tenant_id: int) -> None:
    """清理租户的旧知识库数据（Milvus + ES + DB 记录），为灌入干净数据做准备。

    清理的是 demo 英文占位 chunks（如 "Refund available within 7 days..."），
    它们与中文 query 语义不匹配，导致 RAGAS Context Recall 全 0。
    """
    from app.core.embedding_client import get_es_client, get_milvus_collection

    # Milvus: 按 tenant_id 删除所有旧切片
    col = get_milvus_collection()
    try:
        col.delete(expr=f"tenant_id == {tenant_id}")
        print(f"[clear] Milvus: deleted tenant {tenant_id} chunks")
    except Exception as e:
        print(f"[clear] Milvus warn: {e}")

    # ES: 按 tenant_id 删除所有旧切片
    es = get_es_client()
    try:
        es.delete_by_query(
            index="knowledge_chunks",
            body={"query": {"term": {"tenant_id": tenant_id}}},
            refresh=True,
        )
        print(f"[clear] ES: deleted tenant {tenant_id} chunks")
    except Exception as e:
        print(f"[clear] ES warn: {e}")

    # DB: 删除旧 Document 元数据记录（demo 数据，非生产）
    from sqlalchemy import delete as sa_delete

    from app.core.database import SessionLocal
    from app.models.knowledge_document import KnowledgeDocument

    db = SessionLocal()
    try:
        result = db.execute(
            sa_delete(KnowledgeDocument).where(KnowledgeDocument.tenant_id == tenant_id)
        )
        db.commit()
        print(f"[clear] DB: deleted {result.rowcount} old document records")
    except Exception as e:
        db.rollback()
        print(f"[clear] DB warn: {e}")
    finally:
        db.close()


def seed() -> None:
    from app.core.database import SessionLocal
    from app.core.embedding_client import (
        embed_batches,
        init_es_index,
        init_milvus_collection,
    )
    from app.crud import knowledge as knowledge_crud
    from app.tasks.knowledge_tasks import _index_to_es, _index_to_milvus
    from app.utils.file_parser import parse_and_chunk

    # 确保 collection / index 存在
    init_milvus_collection()
    init_es_index()

    # 清理旧英文占位数据
    clear_existing(TENANT_ID)

    db = SessionLocal()
    total = 0
    try:
        for filename, content in KB_DOCS.items():
            content_bytes = content.encode("utf-8")
            chunks = parse_and_chunk(filename, content_bytes)
            if not chunks:
                print(f"[seed] {filename}: no chunks, skip")
                continue

            vectors = embed_batches([c.text for c in chunks])
            if len(vectors) != len(chunks):
                print(f"[seed] {filename}: vector count mismatch {len(vectors)}/{len(chunks)}, skip")
                continue

            doc = knowledge_crud.create(
                db,
                tenant_id=TENANT_ID,
                filename=filename,
                file_type="md",
                file_size=len(content_bytes),
                version=1,
            )
            db.flush()

            _index_to_milvus(TENANT_ID, doc.id, filename, chunks, vectors)
            _index_to_es(TENANT_ID, doc.id, filename, chunks)

            knowledge_crud.update_status(db, doc, "ready")
            knowledge_crud.set_chunk_count(db, doc, len(chunks))
            db.commit()
            print(f"[seed] {filename}: {len(chunks)} chunks indexed (doc_id={doc.id})")
            total += len(chunks)
        print(f"=== Seed done: {total} chunks total for tenant {TENANT_ID} ===")
    except Exception as e:
        db.rollback()
        print(f"[seed] FAILED: {e}")
        import traceback

        traceback.print_exc()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    seed()
